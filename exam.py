import pandas as pd
import matplotlib.pyplot as plt

from sklearn.metrics import accuracy_score,classification_report
from sklearn.model_selection import train_test_split
from sklearn.tree import DecisionTreeClassifier,plot_tree

url = "https://archive.ics.uci.edu/ml/machine-learning-databases/00352/Online%20Retail.xlsx"
df = pd.read_excel(url)

df=df.dropna(subset=['CustomerID'])
df=df[~df['InvoiceNo'].astype(str).str.startswith('C')]
df=df[(df['Quantity']>0 )& (df['UnitPrice']>0)]

df['CustomerID']=df['CustomerID'].astype(int)
df['Amount']=df['Quantity']*df['UnitPrice']

customer=df.groupby('CustomerID').agg(
    totalspend=('Amount','sum'),
    frequency=('InvoiceNo','nunique'),
    avgquantity=('Quantity','mean'),
    avgprice=('UnitPrice','mean'),
    producttype=('StockCode','nunique')
).reset_index()

customer['segment']=pd.qcut(
    customer['totalspend'].rank(method='first')
    ,q=3,labels=['low','medium','high'])

x=customer[['frequency','avgquantity','avgprice','producttype']]
y=customer['segment']

xtrain,xtest,ytrain,ytest=train_test_split(
    x,y,test_size=0.2,random_state=42,stratify=y
)

model=DecisionTreeClassifier(criterion='entropy',max_depth=4,random_state=42)

model.fit(xtrain,ytrain)
pred=model.predict(xtest)

print("accuracy score: ",accuracy_score(ytest,pred))
print(classification_report(ytest,pred,zero_division=0))

plt.figure(figsize=(18,8))
plot_tree(model,feature_names=x.columns,class_names=[str(c) for c in model.classes_]
          , filled=True, rounded=True)
plt.title('customer segmentation decision tree')
plt.tight_layout()
plt.show()

importance=pd.Series(
    model.feature_importances_,
    index=x.columns
).sort_values(ascending=False)

print("\n Feature Importances\n")
print(importance)

